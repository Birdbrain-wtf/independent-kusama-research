// A deliberately small model. Every input comes from ../assumptions.csv and none is a finding.
// Usage: node model.mjs [--write] [--ksm_price=2.87] [--issuance=4] [--cores=8] [--team_size=2 --engineer_cost=113004] [--seat_hardware=1200 --operator_overhead=1800 --seats_per_operator=1] [--seat_cost=3000] [--seats=96]
// --seat_cost sets one flat figure a seat and overrides the hardware and operator split.
import { readFileSync, writeFileSync } from 'node:fs';

const here = new URL('..', import.meta.url);

function parseCsv(text) {
  const rows = [[]];
  let cell = '', quoted = false;
  for (const ch of text) {
    if (quoted) { if (ch === '"') quoted = false; else cell += ch; }
    else if (ch === '"') quoted = true;
    else if (ch === ',') { rows.at(-1).push(cell); cell = ''; }
    else if (ch === '\n') { rows.at(-1).push(cell); cell = ''; rows.push([]); }
    else cell += ch;
  }
  const [head, ...body] = rows.filter((r) => r.length > 1);
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i] ?? ''])));
}

const rows = parseCsv(readFileSync(new URL('assumptions.csv', here), 'utf8'));
const byName = Object.fromEntries(rows.map((r) => [r.variable, r]));
const num = (name, key = 'base') => Number(byName[name][key]);

const baseInputs = () => ({
  ksm_price: num('ksm_price'), issuance: num('issuance'), cores: num('cores'),
  team_size: num('team_size'), engineer_cost: num('engineer_cost'),
  seat_hardware: num('seat_hardware'), operator_overhead: num('operator_overhead'), seats_per_operator: num('seats_per_operator'),
  outside_revenue: num('outside_revenue'), validators_per_core: num('validators_per_core'),
  minimum_seats: num('minimum_seats'), supply: num('supply'), staked: num('staked'),
  operator_share: num('operator_share'),
});

function run(input) {
  const i = { ...baseInputs(), ...input };
  const seats = i.seats ?? Math.max(i.cores * i.validators_per_core, i.minimum_seats);
  const potKsm = i.supply * i.issuance / 100;
  const pot = potKsm * i.ksm_price + i.outside_revenue;
  const operators = Math.ceil(seats / i.seats_per_operator);
  const seatBill = i.seat_cost ? seats * i.seat_cost * 12 : (seats * i.seat_hardware + operators * i.operator_overhead) * 12;
  const perSeatMonth = seatBill / seats / 12;
  const teamBill = i.team_size * i.engineer_cost;
  const bill = seatBill + teamBill;
  const left = pot - bill;
  return {
    seats, operators, perSeatMonth, potKsm, pot, seatBill, teamBill, bill, left,
    stakerYield: Math.max(left, 0) / (i.staked * i.ksm_price),
    breakEvenPrice: (bill - i.outside_revenue) / potKsm,
    issuanceNeeded: (bill - i.outside_revenue) / i.ksm_price / i.supply * 100,
    seatsPotPays: pot / (perSeatMonth * 12),
    commissionOnlyBreakEven: seatBill / (potKsm * i.operator_share),
    costOfAThird: i.staked / 3 * i.ksm_price,
  };
}

const m = (v) => `${v < 0 ? '-' : ''}US$${(Math.abs(v) / 1e6).toFixed(2)}m`;
const p = (v) => `US$${v.toFixed(2)}`;
const pct = (v) => `${v.toFixed(2)}%`;

const args = Object.fromEntries(process.argv.slice(2).filter((a) => a.includes('=')).map((a) => {
  const [k, v] = a.replace(/^--/, '').split('='); return [k, Number(v)];
}));

