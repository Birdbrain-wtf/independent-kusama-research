  out.push('## What is in it and what is not', '');
  out.push('Income is issuance plus outside revenue, and all of it is treated as available for these bills. The bill is seats only. Engineering is not priced, so every total here is too low until the missing lines are priced. See [`engineering.md`](engineering.md).', '');
