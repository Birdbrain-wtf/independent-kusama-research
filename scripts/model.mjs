  out.push(`| Validator hardware, rented | US$300-500 a month including bandwidth | [Robert Hambrock, forum post](https://forum.polkadot.network/t/proposal-discussion-adapting-kusama-to-demand-and-its-jam-future/17141/23) | From his own validators on today's relay chain, higher outside the EU and US. Hardware only, no labour. The only figure an operator has stated so far |`);
  out.push(`| Metanode | US$2,000 a month, plus 9,000 DOT a year self-stake incentive | [Design proposal for Polkadot](https://forum.polkadot.network/t/19231) | Operating amount for a [metanode](https://docs.polkadot.com/node-infrastructure/run-a-metanode/): validating, collating two chains and serving RPC, on Polkadot's load. Nothing in it is decided. In the seat table above |`);
