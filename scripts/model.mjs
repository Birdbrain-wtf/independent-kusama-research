  for (const r of rows.filter((x) => x.in_total === 'no')) out.push(`- ${r.variable} (${r.id}): ${r.status}`);
  out.push('', '## The base run', '');
  const b = run({});
  out.push('| Figure | Value | Depends on |', '| --- | --- | --- |');
  out.push(`| Pot | ${m(b.pot)} a year (${Math.round(b.potKsm).toLocaleString('en-GB')} KSM) | Issuance (lever), supply (measured), KSM price (external) |`);
  out.push(`| Seats | ${b.seats} | Cores (lever), validators per core and minimum seats (limits) |`);
  out.push(`| Seat bill | ${m(b.seatBill)} a year | Seat cost (untested), seats |`);
  out.push('| Engineering | Not priced | Comes from the tests in [`engineering.md`](engineering.md) |');
  out.push(`| Left for stakers | ${m(b.left)} a year | All of the above |`);
  out.push(`| KSM price at which the pot covers this bill | ${p(b.breakEvenPrice)} | Everything except the price |`);
  out.push(`| Cost of controlling a third of stake | ${m(b.costOfAThird)} | Staked (measured, would move), KSM price (external) |`, '');
  out.push('## If the price moves: nobody here can choose this column', '');
  out.push(`Left for stakers each year, at 32 cores and ${baseSeat} a seat, with nothing for engineering.`, '');
  out.push(`| Issuance (lever) | ${prices.map((x) => `KSM ${p(x)}`).join(' | ')} |`, `| --- | ${prices.map(() => '---').join(' | ')} |`);
  for (const iss of issuances) out.push(`| ${iss}% | ${prices.map((x) => m(run({ ksm_price: x, issuance: iss }).left)).join(' | ')} |`);
  out.push('', `${p(num('ksm_price', 'low'))} and ${p(num('ksm_price', 'high'))} are the 12-month low and high to 25 November 2026, US$4.45 the 12-month median and ${p(num('ksm_price'))} the price on 25 November.`, '');
  out.push('## If the seat cost moves: other people\'s figures', '');
  out.push('At 2.4% issuance, with nothing for engineering. US$2,000 is the metanode rate in a design proposal for Polkadot, for its own load, and US$3,000 is the JAM Prime proposal paper\'s benchmark. Neither has been tested for Kusama.', '');
  out.push(`| Seat cost a month | Cores (seats) | Bill a year | KSM price where the pot covers it | Issuance needed at ${p(num('ksm_price'))} | Seats the pot pays for, no stakers |`, '| --- | --- | --- | --- | --- | --- |');
  for (const sc of seatCosts) for (const c of [8, 32]) {
    const r = run({ seat_cost: sc, cores: c });
    out.push(`| US$${sc.toLocaleString('en-GB')} | ${c} (${r.seats}) | ${m(r.bill)} | ${p(r.breakEvenPrice)} | ${pct(r.issuanceNeeded)} | ${Math.floor(r.seatsPotPays)} |`);
  }
  out.push('', '## If one operator runs several seats: our split, not a finding', '');
  out.push(`The JAM Prime paper prices every seat as its own operation. Its own table splits the US$3,000 into US$1,200 of hosting and bandwidth and US$1,800 of labour, tooling and margin. Here hardware is paid for each seat and the US$1,800 once for each operator. That split is our assumption, and some labour grows with each seat. At 2.4% issuance and 32 cores (96 seats). Kusama today runs about ${num('seats_per_operator', 'high')} seats an operator, as a floor.`, '');
  out.push('| Hardware a seat | Seats an operator | Operators | Cost a seat a month | Bill a year | KSM price where the pot covers it |', '| --- | --- | --- | --- | --- | --- |');
  for (const hw of [num('seat_hardware'), 500, num('seat_hardware', 'low')]) for (const spo of [1, num('seats_per_operator', 'high'), 3]) {
    const r = run({ seat_hardware: hw, seats_per_operator: spo });
    out.push(`| ${usd(hw)} | ${spo} | ${r.operators} | ${usd(Math.round(r.perSeatMonth))} | ${m(r.bill)} | ${p(r.breakEvenPrice)} |`);
  }
  out.push('', `US$1,200 is the JAM Prime paper's hosting line. US$300 and US$500 are the ends of [Robert Hambrock's range](https://forum.polkadot.network/t/proposal-discussion-adapting-kusama-to-demand-and-its-jam-future/17141/23) for renting good validator hardware today, from his own validators. None of them is measured on a JAM node.`);
  out.push('', '## The references being tested', '');
  out.push('Stated by other people for their own scope. None has been tested on Kusama, and none is added to the totals above unless the row says so.', '');
